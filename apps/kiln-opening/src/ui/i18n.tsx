function interpolate(value: string, variables?: Record<string, string | number>): string {
  if (variables === undefined) return value;
  return Object.entries(variables).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
    value,
  );
}

export function translate(
  locale: Locale,
  english: string,
  variables?: Record<string, string | number>,
): string {
  return interpolate(locale === "zh-CN" ? ZH_CN[english] ?? english : english, variables);
}

export function term(locale: Locale, id: string): string {
  return TERM_LABELS[locale][id] ?? id.replaceAll("_", " ");
}

interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (english: string, variables?: Record<string, string | number>) => string;
  term: (id: string) => string;
}

const DEFAULT_LANGUAGE_CONTEXT: LanguageContextValue = {
  locale: "en",
  setLocale: () => undefined,
  t: (english, variables) => translate("en", english, variables),
  term: (id) => term("en", id),
};

const LanguageContext = createContext<LanguageContextValue>(DEFAULT_LANGUAGE_CONTEXT);

function storedLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "zh-CN" ? "zh-CN" : "en";
}

export function LanguageProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => initialLocale ?? storedLocale());
  const setLocale = (next: Locale): void => {
    setLocaleState(next);
    if (typeof window !== "undefined") window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
  };
  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en";
  }, [locale]);
  const value = useMemo<LanguageContextValue>(() => ({
    locale,
    setLocale,
    t: (english, variables) => translate(locale, english, variables),
    term: (id) => term(locale, id),
  }), [locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageContextValue {
  return useContext(LanguageContext);
}

